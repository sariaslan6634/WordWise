using MediatR;
using Microsoft.EntityFrameworkCore;
using System.Text.Json;
using WordWise.Application.Common.Exceptions;
using WordWise.Application.Common.Interfaces;
using WordWise.Application.Features.Clips.Dtos;
using WordWise.Application.Features.Clips.Services;
using WordWise.Domain.Entities;
using WordWise.Domain.Enums;

namespace WordWise.Application.Features.Clips.Commands.GenerateClips
{
    public record GenerateClipsCommand(Guid CandidateId) : IRequest<List<VideoClipDto>>;

    /// <summary>
    /// 1) Altyazıyı çeker, 2) klip seçici ajan ile 5-6 tek cümlelik kesit seçer,
    /// 3) kalite kontrolcü ajan ile her kesite uygun / uygun değil kararı verir, 4) kaydeder.
    /// </summary>
    public class GenerateClipsCommandHandler(
        IWordWiseDbContext _context,
        ICaptionService _captionService,
        IVideoDetailsService _detailsService)
        : IRequestHandler<GenerateClipsCommand, List<VideoClipDto>>
    {
        public async Task<List<VideoClipDto>> Handle(GenerateClipsCommand request, CancellationToken cancellationToken)
        {
            var candidate = await _context.VideoCandidates
                .FirstOrDefaultAsync(x => x.Id == request.CandidateId, cancellationToken);
            if (candidate is null)
                throw new NotFoundException(nameof(VideoCandidate), request.CandidateId);

            var track = await _captionService.GetCaptionsAsync(candidate.YoutubeId, cancellationToken);
            if (track is null || track.Lines.Count == 0)
                throw new BusinessException("Bu video için İngilizce altyazı bulunamadı.");

            var details = await _detailsService.GetVideoDetailsAsync(candidate.YoutubeId, cancellationToken);
            if (details is null)
                throw new BusinessException("Video bilgileri YouTube'dan alınamadı (video silinmiş veya gizli olabilir).");

            var picked = ClipSelector.Select(track.Lines, videoDurationSec: details.DurationSeconds);

            // Önceki üretimleri sil (yeniden üretimde kopya birikmesin)
            var previous = await _context.VideoClips
                .Where(x => x.VideoCandidateId == candidate.Id)
                .ToListAsync(cancellationToken);
            foreach (var old in previous) old.IsDeleted = true;

            var created = new List<VideoClip>();
            foreach (var clip in picked)
            {
                var qc = ClipQualityChecker.Check(clip, details, track);
                var entity = new VideoClip
                {
                    VideoCandidateId = candidate.Id,
                    YoutubeId = candidate.YoutubeId,
                    StartSec = clip.Start,
                    EndSec = clip.End,
                    Text = clip.Text,
                    WordTimingsJson = JsonSerializer.Serialize(clip.Words, VideoClipMapper.JsonOptions),
                    IsAutoCaption = track.IsAutoGenerated,
                    QcStatus = qc.Passed ? ClipQcStatus.Passed : ClipQcStatus.Failed,
                    QcReasons = qc.Reasons.Count > 0 ? string.Join("\n", qc.Reasons) : null,
                    QcWarnings = qc.Warnings.Count > 0 ? string.Join("\n", qc.Warnings) : null,
                };
                created.Add(entity);
                await _context.VideoClips.AddAsync(entity, cancellationToken);
            }

            await _context.SaveChangesAsync(cancellationToken);
            return created.Select(VideoClipMapper.ToDto).ToList();
        }
    }
}
