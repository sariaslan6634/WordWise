using Microsoft.EntityFrameworkCore;
using System.Text.Json;
using System.Text.RegularExpressions;
using WordWise.Application.Common.Exceptions;
using WordWise.Application.Common.Interfaces;
using WordWise.Application.Features.Clips.Dtos;
using WordWise.Domain.Entities;
using WordWise.Domain.Enums;

namespace WordWise.Application.Features.Clips.Services
{
    /// <summary>Altyazı çek → klip seç → kalite kontrol et → kaydet akışı (aday videodan veya doğrudan YouTube bağlantısından).</summary>
    public class ClipGenerator(
        IWordWiseDbContext _context,
        ICaptionService _captionService,
        IVideoDetailsService _detailsService)
    {
        private static readonly Regex IdRegex = new(@"^[A-Za-z0-9_-]{11}$", RegexOptions.Compiled);
        private static readonly Regex UrlIdRegex = new(
            @"(?:v=|youtu\.be/|/shorts/|/embed/|/live/)([A-Za-z0-9_-]{11})", RegexOptions.Compiled);

        /// <summary>YouTube bağlantısından veya düz kimlikten 11 karakterlik video kimliğini çıkarır. Bulamazsa null.</summary>
        public static string? ExtractYoutubeId(string? input)
        {
            if (string.IsNullOrWhiteSpace(input)) return null;
            var trimmed = input.Trim();
            if (IdRegex.IsMatch(trimmed)) return trimmed;
            var match = UrlIdRegex.Match(trimmed);
            return match.Success ? match.Groups[1].Value : null;
        }

        public async Task<List<VideoClipDto>> GenerateAsync(
            string youtubeId, Guid? candidateId, CancellationToken cancellationToken)
        {
            var track = await _captionService.GetCaptionsAsync(youtubeId, cancellationToken);
            if (track is null || track.Lines.Count == 0)
                throw new BusinessException("Bu video için İngilizce altyazı bulunamadı (videoda altyazı olmayabilir veya YouTube altyazıyı vermedi; API günlüklerine bakın).");

            var details = await _detailsService.GetVideoDetailsAsync(youtubeId, cancellationToken);
            if (details is null)
                throw new BusinessException("Video bilgileri YouTube'dan alınamadı (video silinmiş/gizli olabilir veya API anahtarı hatalı).");

            var picked = ClipSelector.Select(track.Lines, videoDurationSec: details.DurationSeconds);

            // Aynı videodan yayınlanmamış önceki üretimleri sil (yeniden üretimde kopya birikmesin).
            // Yayınlanmış klipler korunur; aynı cümle tekrar eklenmez.
            var previous = await _context.VideoClips
                .Where(x => x.YoutubeId == youtubeId)
                .ToListAsync(cancellationToken);
            foreach (var old in previous.Where(x => !x.IsPublished)) old.IsDeleted = true;
            var publishedKeys = previous.Where(x => x.IsPublished)
                .Select(x => ClipSelector.Normalize(x.Text)).ToHashSet();

            var created = new List<VideoClip>();
            foreach (var clip in picked)
            {
                if (publishedKeys.Contains(ClipSelector.Normalize(clip.Text))) continue;
                var qc = ClipQualityChecker.Check(clip, details, track);
                var entity = new VideoClip
                {
                    VideoCandidateId = candidateId,
                    YoutubeId = youtubeId,
                    SourceTitle = details.Title.Length > 500 ? details.Title[..500] : details.Title,
                    StartSec = clip.Start,
                    EndSec = clip.End,
                    Text = clip.Text,
                    WordTimingsJson = JsonSerializer.Serialize(clip.Words, VideoClipMapper.JsonOptions),
                    IsAutoCaption = track.IsAutoGenerated,
                    QcStatus = qc.Passed ? ClipQcStatus.Passed : ClipQcStatus.Failed,
                    QcReasons = qc.Reasons.Count > 0 ? string.Join("\n", qc.Reasons) : null,
                    QcWarnings = qc.Warnings.Count > 0 ? string.Join("\n", qc.Warnings) : null,
                };
                created.Add(entity);
                await _context.VideoClips.AddAsync(entity, cancellationToken);
            }

            await _context.SaveChangesAsync(cancellationToken);
            return created.Select(VideoClipMapper.ToDto).ToList();
        }
    }
}
