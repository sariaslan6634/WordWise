using WordWise.Application.Features.Clips.Models;

namespace WordWise.Application.Features.Clips.Services
{
    /// <summary>
    /// Kalite kontrolcü ajan: bir klibin "uygun / uygun değil" kararını ve nedenlerini üretir.
    /// Denetimler: video kalitesi, altyazı-video uyumu (zamanlama sezgileri), küfür, yetişkin içerik.
    /// Not: Ses tanıma veya görüntü analizi yapmaz; kararlar YouTube meta verisi ve altyazı metnine dayanır.
    /// </summary>
    public static class ClipQualityChecker
    {
        private const double MinWordsPerSecond = 1.0;
        private const double MaxWordsPerSecond = 5.0;
        private const double ContextSec = 2.0;

        public static QcResult Check(ClipCandidate clip, VideoDetails details, CaptionTrack track)
        {
            var reasons = new List<string>();
            var warnings = new List<string>();

            CheckVideoQuality(details, reasons);
            CheckCaptionSync(clip, details, track, reasons, warnings);
            CheckProfanity(clip, details, track, reasons);
            CheckAdultContent(clip, details, track, reasons);

            return new QcResult(reasons.Count == 0, reasons, warnings);
        }

        private static void CheckVideoQuality(VideoDetails details, List<string> reasons)
        {
            if (!string.Equals(details.Definition, "hd", StringComparison.OrdinalIgnoreCase))
                reasons.Add("Video kalitesi düşük: HD (en az 720p) değil.");
            if (!details.IsEmbeddable)
                reasons.Add("Video başka sitelerde oynatılmaya (embed) izin vermiyor.");
            if (!string.Equals(details.PrivacyStatus, "public", StringComparison.OrdinalIgnoreCase))
                reasons.Add($"Video herkese açık değil (durum: {details.PrivacyStatus}).");
        }

        private static void CheckCaptionSync(
            ClipCandidate clip, VideoDetails details, CaptionTrack track,
            List<string> reasons, List<string> warnings)
        {
            if (track.Lines.Count == 0)
            {
                reasons.Add("Videonun altyazısı bulunamadı; metin ile video eşleştirilemiyor.");
                return;
            }

            if (details.DurationSeconds > 0 && clip.End > details.DurationSeconds + 1)
                reasons.Add("Klibin bitişi video süresinin dışında kalıyor; altyazı zamanları videoyla uyuşmuyor.");

            if (clip.Words.Count > 0)
            {
                var span = Math.Max(0.1, clip.Words[^1].End - clip.Words[0].Start);
                var rate = clip.Words.Count / span;
                if (rate < MinWordsPerSecond || rate > MaxWordsPerSecond)
                    reasons.Add($"Konuşma hızı gerçekçi değil ({rate:0.0} kelime/sn); altyazı zamanlaması videoyla uyuşmuyor olabilir.");
            }

            var clipKey = ClipSelector.Normalize(clip.Text);
            var foreign = track.Lines.Where(l =>
            {
                var overlap = Math.Min(l.End, clip.End) - Math.Max(l.Start, clip.Start);
                if (overlap <= 0.5) return false;
                var cleaned = ClipSelector.Clean(l.Text);
                if (ClipSelector.WordCount(cleaned) < 2) return false;
                return !clipKey.Contains(ClipSelector.Normalize(cleaned));
            }).ToList();
            if (foreign.Count > 0)
                reasons.Add("Klibin zaman aralığında seçilen cümleden farklı altyazı satırları da var (üst üste konuşma veya zamanlama kayması).");

            if (clip.CaptionSeconds > 0 && clip.Words.Count > 0 && clip.Words.Count / clip.CaptionSeconds < 0.7)
                warnings.Add($"Altyazı ekranda {clip.CaptionSeconds:0.#} sn kalmış ama cümle çok daha kısa sürüyor; konuşma süresi tahmin edildi, kelime vurgusunu kontrol edin.");

            if (track.IsAutoGenerated)
                warnings.Add("Altyazı YouTube'un otomatik altyazısı; yazım hataları olabilir, kontrol edin.");
        }

        private static IEnumerable<string> NearbyText(ClipCandidate clip, CaptionTrack track) =>
            track.Lines
                .Where(l => l.End >= clip.Start - ContextSec && l.Start <= clip.End + ContextSec)
                .Select(l => ClipSelector.Clean(l.Text));

        private static void CheckProfanity(ClipCandidate clip, VideoDetails details, CaptionTrack track, List<string> reasons)
        {
            var inClip = ContentFilters.FindProfanity(clip.Text);
            var nearby = ContentFilters.FindProfanity(string.Join(" ", NearbyText(clip, track)));
            var meta = ContentFilters.FindProfanity($"{details.Title} {details.Description} {string.Join(" ", details.Tags)}");

            if (inClip.Count > 0)
                reasons.Add($"Seçilen cümlede küfür var: {string.Join(", ", inClip)}.");
            else if (nearby.Count > 0)
                reasons.Add($"Klibin hemen öncesinde/sonrasında küfür var: {string.Join(", ", nearby)}.");
            if (meta.Count > 0)
                reasons.Add($"Video başlığı/açıklaması/etiketlerinde küfür var: {string.Join(", ", meta)}.");
        }

        private static void CheckAdultContent(ClipCandidate clip, VideoDetails details, CaptionTrack track, List<string> reasons)
        {
            if (details.AgeRestricted)
                reasons.Add("YouTube bu videoyu yaş sınırlı (18+) olarak işaretlemiş.");

            var meta = ContentFilters.FindAdultTerms($"{details.Title} {details.Description} {string.Join(" ", details.Tags)}");
            if (meta.Count > 0)
                reasons.Add($"Video başlığı/açıklaması/etiketlerinde yetişkin içerik ifadeleri var: {string.Join(", ", meta)}.");

            var text = ContentFilters.FindAdultTerms($"{clip.Text} {string.Join(" ", NearbyText(clip, track))}");
            if (text.Count > 0)
                reasons.Add($"Klip ve çevresindeki konuşmada yetişkin içerik ifadeleri var: {string.Join(", ", text)}.");
        }
    }
}
