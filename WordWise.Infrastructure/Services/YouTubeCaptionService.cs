using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;
using System.Diagnostics;
using System.Text;
using System.Text.RegularExpressions;
using WordWise.Application.Common.Interfaces;
using WordWise.Application.Common.Settings;
using WordWise.Application.Features.Clips.Models;

namespace WordWise.Infrastructure.Services
{
    /// <summary>
    /// YouTube'dan İngilizce altyazıyı iki yoldan dener: (1) izleme sayfası, (2) InnerTube player API (Android istemcisi).
    /// Resmî bir API değildir; YouTube değiştirirse bozulabilir. Her adım ayrıntılı günlüğe yazılır.
    /// </summary>
    public class YouTubeCaptionService(
        HttpClient _httpClient,
        IOptions<YoutubeSettings> _options,
        ILogger<YouTubeCaptionService> _logger) : ICaptionService
    {
        private const string WebUserAgent =
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";
        private const string AndroidUserAgent = "com.google.android.youtube/20.10.38 (Linux; U; Android 11) gzip";

        public async Task<CaptionTrack?> GetCaptionsAsync(string youtubeId, CancellationToken cancellationToken = default)
        {
            var sources = new (string Name, Func<Task<string>> Fetch)[]
            {
                ("izleme sayfası", () => FetchWatchPageAsync(youtubeId, cancellationToken)),
                ("innertube-android", () => FetchInnerTubeAsync(youtubeId, cancellationToken)),
            };

            foreach (var (name, fetch) in sources)
            {
                try
                {
                    var body = await fetch();
                    var tracks = CaptionParser.ExtractEnglishTracks(body);
                    if (tracks.Count == 0)
                    {
                        _logger.LogWarning(
                            "[{Source}] {VideoId}: İngilizce altyazı parçası yok. Yanıt uzunluğu: {Length}, captionTracks var mı: {HasTracks}, consent: {IsConsent}, bot/giriş doğrulaması: {IsBotCheck}, playabilityStatus: {Playability}",
                            name, youtubeId, body.Length, body.Contains("captionTracks"),
                            body.Contains("consent.youtube.com"),
                            body.Contains("confirm you") || body.Contains("not a bot") || body.Contains("LOGIN_REQUIRED"),
                            Snippet(body, "\"playabilityStatus\""));
                        continue;
                    }

                    foreach (var track in tracks)
                    {
                        var json = await FetchTimedTextAsync(track.BaseUrl, cancellationToken);
                        if (string.IsNullOrWhiteSpace(json))
                        {
                            _logger.LogWarning("[{Source}] {VideoId}: {Lang} altyazı içeriği boş döndü (YouTube istemciyi reddetmiş olabilir).", name, youtubeId, track.Language);
                            continue;
                        }

                        var lines = CaptionParser.ParseJson3(json);
                        if (lines.Count > 0)
                        {
                            _logger.LogInformation("[{Source}] {VideoId}: {Count} altyazı satırı alındı (otomatik: {Auto}).", name, youtubeId, lines.Count, track.IsAutoGenerated);
                            return new CaptionTrack(track.Language, track.IsAutoGenerated, lines);
                        }

                        _logger.LogWarning("[{Source}] {VideoId}: altyazı içeriği ayrıştırılamadı. İlk 200 karakter: {Head}", name, youtubeId, json.Length > 200 ? json[..200] : json);
                    }
                }
                catch (Exception ex)
                {
                    _logger.LogError(ex, "[{Source}] {VideoId}: altyazı alınırken hata oluştu.", name, youtubeId);
                }
            }

            return await TryYtDlpAsync(youtubeId, cancellationToken);
        }

        /// <summary>Son çare: bilgisayarda kurulu yt-dlp ile altyazıyı indirir (YouTube değişikliklerine en hızlı uyum sağlayan araç).</summary>
        private async Task<CaptionTrack?> TryYtDlpAsync(string youtubeId, CancellationToken ct)
        {
            if (!Regex.IsMatch(youtubeId, "^[A-Za-z0-9_-]{11}$")) return null;

            var exe = string.IsNullOrWhiteSpace(_options.Value.YtDlpPath) ? "yt-dlp" : _options.Value.YtDlpPath;
            foreach (var auto in new[] { false, true })
            {
                var dir = Path.Combine(Path.GetTempPath(), "wordwise-captions", Guid.NewGuid().ToString("N"));
                Directory.CreateDirectory(dir);
                try
                {
                    var psi = new ProcessStartInfo(exe)
                    {
                        RedirectStandardOutput = true,
                        RedirectStandardError = true,
                        UseShellExecute = false,
                        CreateNoWindow = true,
                    };
                    foreach (var arg in new[]
                    {
                        "--skip-download", auto ? "--write-auto-subs" : "--write-subs",
                        "--sub-langs", "en.*", "--sub-format", "json3",
                        "--no-playlist", "--no-warnings",
                        "-o", Path.Combine(dir, "%(id)s"),
                        $"https://www.youtube.com/watch?v={youtubeId}"
                    })
                        psi.ArgumentList.Add(arg);

                    using var process = Process.Start(psi);
                    if (process is null) continue;

                    using var timeout = CancellationTokenSource.CreateLinkedTokenSource(ct);
                    timeout.CancelAfter(TimeSpan.FromSeconds(90));
                    var stderrTask = process.StandardError.ReadToEndAsync(timeout.Token);
                    var stdoutTask = process.StandardOutput.ReadToEndAsync(timeout.Token);
                    await process.WaitForExitAsync(timeout.Token);
                    var stderr = await stderrTask;
                    await stdoutTask;

                    var file = Directory.GetFiles(dir, "*.json3").OrderBy(f => f).FirstOrDefault();
                    if (file is null)
                    {
                        _logger.LogWarning("[yt-dlp] {VideoId}: ({Mode}) altyazı dosyası oluşmadı. Çıkış kodu: {Code}. Hata: {Err}",
                            youtubeId, auto ? "otomatik" : "elle girilmiş", process.ExitCode, stderr.Length > 400 ? stderr[..400] : stderr);
                        continue;
                    }

                    var lines = CaptionParser.ParseJson3(await File.ReadAllTextAsync(file, ct));
                    if (lines.Count == 0) continue;

                    _logger.LogInformation("[yt-dlp] {VideoId}: {Count} altyazı satırı alındı (otomatik: {Auto}).", youtubeId, lines.Count, auto);
                    return new CaptionTrack("en", auto, lines);
                }
                catch (System.ComponentModel.Win32Exception)
                {
                    _logger.LogWarning("[yt-dlp] '{Exe}' bulunamadı. yt-dlp kurulu değil veya PATH'te değil (appsettings: YouTubeSettings:YtDlpPath).", exe);
                    return null;
                }
                catch (Exception ex)
                {
                    _logger.LogError(ex, "[yt-dlp] {VideoId}: çalıştırılırken hata oluştu.", youtubeId);
                }
                finally
                {
                    try { Directory.Delete(dir, true); } catch (IOException) { }
                }
            }
            return null;
        }

        private static string Snippet(string body, string marker)
        {
            var i = body.IndexOf(marker, StringComparison.Ordinal);
            if (i < 0) return "(yok)";
            return body.Substring(i, Math.Min(160, body.Length - i));
        }

        private async Task<string> FetchWatchPageAsync(string youtubeId, CancellationToken ct)
        {
            using var request = new HttpRequestMessage(HttpMethod.Get, $"https://www.youtube.com/watch?v={Uri.EscapeDataString(youtubeId)}&hl=en");
            request.Headers.TryAddWithoutValidation("User-Agent", WebUserAgent);
            request.Headers.TryAddWithoutValidation("Accept-Language", "en-US,en;q=0.9");
            request.Headers.TryAddWithoutValidation("Cookie", "CONSENT=YES+1; SOCS=CAI");
            return await SendAsync(request, ct);
        }

        private async Task<string> FetchInnerTubeAsync(string youtubeId, CancellationToken ct)
        {
            var payload = "{\"context\":{\"client\":{\"clientName\":\"ANDROID\",\"clientVersion\":\"20.10.38\",\"androidSdkVersion\":30,\"hl\":\"en\",\"gl\":\"US\"}},\"videoId\":\""
                          + youtubeId + "\"}";
            using var request = new HttpRequestMessage(HttpMethod.Post, "https://www.youtube.com/youtubei/v1/player?prettyPrint=false")
            {
                Content = new StringContent(payload, Encoding.UTF8, "application/json")
            };
            request.Headers.TryAddWithoutValidation("User-Agent", AndroidUserAgent);
            request.Headers.TryAddWithoutValidation("Accept-Language", "en-US,en;q=0.9");
            return await SendAsync(request, ct);
        }

        private async Task<string> FetchTimedTextAsync(string baseUrl, CancellationToken ct)
        {
            var url = baseUrl.Contains("fmt=") ? baseUrl : baseUrl + "&fmt=json3";
            using var request = new HttpRequestMessage(HttpMethod.Get, url);
            request.Headers.TryAddWithoutValidation("User-Agent", WebUserAgent);
            request.Headers.TryAddWithoutValidation("Accept-Language", "en-US,en;q=0.9");
            try { return await SendAsync(request, ct); }
            catch (HttpRequestException ex)
            {
                _logger.LogWarning(ex, "timedtext isteği başarısız oldu: {Status}", ex.StatusCode);
                return string.Empty;
            }
        }

        private async Task<string> SendAsync(HttpRequestMessage request, CancellationToken ct)
        {
            using var response = await _httpClient.SendAsync(request, ct);
            response.EnsureSuccessStatusCode();
            return await response.Content.ReadAsStringAsync(ct);
        }
    }
}
