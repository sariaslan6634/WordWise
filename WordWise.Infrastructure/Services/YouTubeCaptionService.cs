using Microsoft.Extensions.Logging;
using WordWise.Application.Common.Interfaces;
using WordWise.Application.Features.Clips.Models;

namespace WordWise.Infrastructure.Services
{
    /// <summary>
    /// YouTube izleme sayfasındaki altyazı parçalarını okur. Resmî bir API değildir;
    /// YouTube sayfa/altyazı biçimini değiştirirse bozulabilir (hata durumunda null döner).
    /// </summary>
    public class YouTubeCaptionService(HttpClient _httpClient, ILogger<YouTubeCaptionService> _logger) : ICaptionService
    {
        private const string UserAgent =
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";

        public async Task<CaptionTrack?> GetCaptionsAsync(string youtubeId, CancellationToken cancellationToken = default)
        {
            try
            {
                var html = await GetStringAsync($"https://www.youtube.com/watch?v={Uri.EscapeDataString(youtubeId)}&hl=en", cancellationToken);
                var tracks = CaptionParser.ExtractEnglishTracks(html);
                if (tracks.Count == 0)
                {
                    _logger.LogWarning(
                        "{VideoId} için İngilizce altyazı parçası bulunamadı. Sayfa uzunluğu: {Length}, captionTracks var mı: {HasTracks}, onay/consent sayfası mı: {IsConsent}, giriş/bot doğrulaması mı: {IsBotCheck}",
                        youtubeId, html.Length, html.Contains("captionTracks"),
                        html.Contains("consent.youtube.com"), html.Contains("confirm you") || html.Contains("not a bot"));
                    return null;
                }

                var track = tracks[0];
                var json = await GetStringAsync(track.BaseUrl + "&fmt=json3", cancellationToken);
                if (string.IsNullOrWhiteSpace(json))
                {
                    _logger.LogWarning("{VideoId} altyazı içeriği boş döndü.", youtubeId);
                    return null;
                }

                var lines = CaptionParser.ParseJson3(json);
                return lines.Count == 0 ? null : new CaptionTrack(track.Language, track.IsAutoGenerated, lines);
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "{VideoId} için altyazı alınırken hata oluştu.", youtubeId);
                return null;
            }
        }

        private async Task<string> GetStringAsync(string url, CancellationToken cancellationToken)
        {
            using var request = new HttpRequestMessage(HttpMethod.Get, url);
            request.Headers.TryAddWithoutValidation("User-Agent", UserAgent);
            request.Headers.TryAddWithoutValidation("Accept-Language", "en-US,en;q=0.9");
            request.Headers.TryAddWithoutValidation("Cookie", "CONSENT=YES+1; SOCS=CAI");

            using var response = await _httpClient.SendAsync(request, cancellationToken);
            response.EnsureSuccessStatusCode();
            return await response.Content.ReadAsStringAsync(cancellationToken);
        }
    }
}
