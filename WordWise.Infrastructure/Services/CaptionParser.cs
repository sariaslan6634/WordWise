using System.Net;
using System.Text.Json;
using WordWise.Application.Features.Clips.Models;

namespace WordWise.Infrastructure.Services
{
    public record CaptionTrackInfo(string BaseUrl, string Language, bool IsAutoGenerated);

    /// <summary>YouTube izleme sayfasından altyazı parçalarını ve json3 altyazı içeriğini ayrıştırır.</summary>
    public static class CaptionParser
    {
        /// <summary>İzleme sayfası HTML'indeki "captionTracks" dizisinden İngilizce parçaları döner (elle girilmiş olanlar önde).</summary>
        public static List<CaptionTrackInfo> ExtractEnglishTracks(string html)
        {
            var result = new List<CaptionTrackInfo>();
            var markerMatch = System.Text.RegularExpressions.Regex.Match(html, "\"captionTracks\"\\s*:");
            if (!markerMatch.Success) return result;

            var arrayText = ExtractJsonArray(html, markerMatch.Index + markerMatch.Length);
            if (arrayText is null) return result;

            using var doc = JsonDocument.Parse(arrayText);
            foreach (var item in doc.RootElement.EnumerateArray())
            {
                var baseUrl = item.TryGetProperty("baseUrl", out var b) ? b.GetString() : null;
                var lang = item.TryGetProperty("languageCode", out var l) ? l.GetString() : null;
                var kind = item.TryGetProperty("kind", out var k) ? k.GetString() : null;
                if (string.IsNullOrEmpty(baseUrl) || string.IsNullOrEmpty(lang)) continue;
                if (!lang.StartsWith("en", StringComparison.OrdinalIgnoreCase)) continue;

                result.Add(new CaptionTrackInfo(baseUrl, lang, string.Equals(kind, "asr", StringComparison.OrdinalIgnoreCase)));
            }

            return result.OrderBy(t => t.IsAutoGenerated).ToList();
        }

        /// <summary>Metindeki startIndex'ten itibaren ilk '[' ile eşleşen ']' arasını döner (tırnak içindekileri atlar).</summary>
        public static string? ExtractJsonArray(string text, int startIndex)
        {
            var begin = text.IndexOf('[', startIndex);
            if (begin < 0) return null;

            var depth = 0;
            var inString = false;
            for (var i = begin; i < text.Length; i++)
            {
                var c = text[i];
                if (inString)
                {
                    if (c == '\\') i++;
                    else if (c == '"') inString = false;
                    continue;
                }
                if (c == '"') inString = true;
                else if (c == '[') depth++;
                else if (c == ']' && --depth == 0) return text.Substring(begin, i - begin + 1);
            }
            return null;
        }

        /// <summary>fmt=json3 altyazı içeriğini satırlara çevirir. Otomatik altyazıda kelime zamanları varsa onları da doldurur.</summary>
        public static List<CaptionLine> ParseJson3(string json)
        {
            var lines = new List<CaptionLine>();
            using var doc = JsonDocument.Parse(json);
            if (!doc.RootElement.TryGetProperty("events", out var events)) return lines;

            foreach (var ev in events.EnumerateArray())
            {
                if (!ev.TryGetProperty("segs", out var segs)) continue;
                if (!ev.TryGetProperty("tStartMs", out var startEl)) continue;

                var start = startEl.GetInt64() / 1000.0;
                var duration = ev.TryGetProperty("dDurationMs", out var durEl) ? durEl.GetInt64() / 1000.0 : 0;

                var parts = new List<(string Text, double Offset)>();
                foreach (var seg in segs.EnumerateArray())
                {
                    var text = seg.TryGetProperty("utf8", out var u) ? u.GetString() ?? "" : "";
                    var offset = seg.TryGetProperty("tOffsetMs", out var o) ? o.GetInt64() / 1000.0 : 0;
                    parts.Add((text, offset));
                }

                var full = WebUtility.HtmlDecode(string.Concat(parts.Select(p => p.Text)).Replace('\n', ' ')).Trim();
                if (full.Length == 0) continue;
                if (duration <= 0) duration = 2.0;

                List<CaptionWord>? words = null;
                var wordParts = parts.Where(p => !string.IsNullOrWhiteSpace(p.Text)).ToList();
                if (wordParts.Count > 1 && wordParts.Any(p => p.Offset > 0))
                {
                    words = new List<CaptionWord>();
                    for (var i = 0; i < wordParts.Count; i++)
                    {
                        var wStart = start + wordParts[i].Offset;
                        var wEnd = i + 1 < wordParts.Count ? start + wordParts[i + 1].Offset : start + duration;
                        words.Add(new CaptionWord(wordParts[i].Text.Trim(), wStart, Math.Max(wEnd, wStart)));
                    }
                }

                lines.Add(new CaptionLine(start, duration, full, words));
            }

            // Üst üste binen satırları kısalt (otomatik altyazılarda kayan pencere nedeniyle)
            lines = lines.OrderBy(l => l.Start).ToList();
            for (var i = 0; i + 1 < lines.Count; i++)
            {
                if (lines[i].End > lines[i + 1].Start)
                    lines[i] = lines[i] with { Duration = Math.Max(0.1, lines[i + 1].Start - lines[i].Start) };
            }
            return lines;
        }
    }
}
